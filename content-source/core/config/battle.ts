/**
 * 戰役的規則（33）★ 全部 GREYBOX。
 *
 * ── 主角的施放次數 ──────────────────────────────────
 * `[1, 0.6, 0.3]` ＝ 保底一招 ＋ 第二招 60% ＋ 第三招 30%，三次獨立擲：
 *
 *   1 招 28% ／ **2 招 54%** ／ 3 招 18%　→ 期望 1.9 招／回合
 *
 * 第一項必須是 1 —— **保底一招**是機制本體（下限由玩家自己保證），
 * 由載入期驗證強制。
 *
 * 而「先擲次數、再抽哪一招、同回合不重複」讓三格的期望上場率相同
 * （各約 0.63 次／回合）。於是配置從「排優先序」變成【設計一組組合】——
 * 三招之間必須各自成立，因為你不知道哪一招會出。
 *
 * ── 指揮傳令的機率 ──────────────────────────────────
 * 三人同階的期望：相識 0.45 ／ 友好 0.90 ／ 知交 1.50 ／ 莫逆 2.10。
 * 加上主角的 1.9，從相識到莫逆【一回合的行動數幾乎翻倍】，
 * 而且過半數的行動來自別人 —— 好感因此不再是一個百分比加成，
 * 而是「你的軍隊每回合能做幾件事」。
 *
 * `baseStartAffinity = 20` 表示所有人開局就在相識，因此第一場戰役
 * 就偶爾有人傳令來，不會是死的。
 *
 * ── 敵方曲線：索引【章節】，數字從【預期能力值】反推（D64）★★ ──
 *
 * 這條索引改過兩次。第一版索引官階（D25），理由抄自 17 §6.4
 * 「難度與報酬必須一起長」—— 但那條規矩講的是委託報酬，
 * 類推到敵人身上沒有依據。而它有實測的壞處：官階一旦被本輪上限封住，
 * 敵人跟著凍住，玩家卻照樣練上去 —— 第一輪就輕鬆打到第七關。
 *
 * **也不能改成「執行期讀四維」**：那是等級同步，練越高對面越強，
 * 養成整個白做。對標必須發生在【設計時】—— 就是下面這張表。
 *
 * ── 對標表（scripts/benchmark.ts，25 輪／組）★ ────────
 * 走到每一章的戰役、配置完成那一刻，玩家實際帶著什麼：
 *
 *   星階  章   主維   兵量   有效軍勢   每回合輸出
 *    無   1     38    186      404         103
 *    無   2     47    254      519         184
 *    無   3     55    426      825         364
 *    無   4     67    829     1864         967
 *    5★  4     75   1884     4995        6083
 *
 * 「有效軍勢」＝ 兵量 ＋ 糧秣換得回的（§5.3）。
 * **戰力預算 ＝ 有效軍勢 × 每回合輸出** —— 這一章總共吸收得起多少傷害。
 *
 * ── 反推 ───────────────────────────────────────────
 * 打完第 K 關累計吃到的傷害：
 *
 *   Σ (敵兵ᵢ / 我方輸出) × 敵輸出ᵢ
 *     ＝ (兵力基準 × 輸出基準 / 我方輸出) × Σ TROOPS_MULᵢ·DAMAGE_MULᵢ
 *     ＝ (兵力基準 × 輸出基準 / 我方輸出) × cum(K)
 *
 * 令它等於有效軍勢，解出【兵力基準 × 輸出基準】。
 * 目標 K ＝ **無星第一輪停在第 2–3 關**，取 cum(2.5)（見 build.ts）。
 * 再用「平手關（TROOPS_MUL 1.0）打五回合」把乘積拆成兩條：
 *
 *   兵力基準 ＝ 5 × 我方輸出
 *   輸出基準 ＝ 有效軍勢 / (5 × cum(2.5))
 *
 * ── 閉式解只給【起點】，最後的數字是量出來的 ★★ ──────
 * 上面那條解出來的基準實測太重（無星只打到 0.70 關），因為它漏了三件
 * 都在加重玩家負擔、而且都難以解析地寫進去的事：
 *
 *   1. 關底敵將**每回合多打一下**，而且那一下也乘 dmgBase
 *   2. 兵量掉下去我方輸出跟著掉 —— 死亡螺旋。閉式解假設輸出恆定
 *   3. 「有效軍勢」裡的糧秣要花招式格去換，那些回合不輸出
 *
 * 一開始用「一個全域校準常數 k」去吸收它，直到 `scripts/calibrate.ts`
 * 加上**每章分開報告**才看見真相：**那個誤差不是全域的，是逐章的。**
 *
 *   同一組 k 之下，無星每章打到　第1章 3.7　第2章 4.5　第3章 1.5　第4章 0.6
 *
 * 病根就是上面第 1 條：第三、四章的戰役各有**四位**關底敵將
 * （第一、二章只有三位），而每位每回合都多打一下。那是**內容的性質**，
 * 一條全域常數吸收不了它。
 *
 * 所以下面兩排是【逐章擬合】的，對著量到的深度調，目標是
 * **無星每一章都停在 2.5–3 關**：
 *
 *   無星 每章打到　第1章 2.9　第2章 2.8　第3章 2.2　第4章 3.0　（平均 2.73）
 *   3★               5.0       5.7       5.5       6.0　（全清率 37%）
 *   4★               5.5       6.0       6.0       6.2　（全清率 46%）
 *   5★               6.3       6.4       6.5       6.5　（全清率 69%）
 *
 * ── 為什麼看全清率而不是平均深度 ★ ──────────────────
 * 玩家講的是「**穩定**過第七關」。平均深度會被 7 這個天花板壓平，
 * 所以真正要對的指標是全清率。無星 **1%** —— 第一輪連一次七關全清
 * 都不會發生，那道牆存在，而且是靠養成拆的，不是靠運氣。
 *
 * **未達標的一端**：4★ 只有 46%、5★ 69%，而使用者要的是
 * 「大部分四星有的五星 → 穩定過第七關」。差距的來源是
 * **星階在前段章節幾乎買不到東西**（5★ 第一章的兵量 196 對無星 186），
 * 而關卡階梯要求的跨度比星階買得到的大。已把 build.ts 的斜率從
 * 1.36 壓到 1.30（5★ 全清率 63% → 69%），再壓下去
 * push-your-luck 會退化成「過得了第一關就過得了第七關」。
 * **要真的到八成，得讓星階在前段就有感 —— 那是內容決定，不是校準。**
 *
 * ── 改動守則 ★ ─────────────────────────────────────
 * **不要單獨改其中一格。** 要嘛逐章重新擬合（跑 calibrate.ts 看每章深度），
 * 要嘛改 build.ts 的斜率（那條管「星階買得動幾關」）。
 *
 * ── 這張表會隨著【功績階梯】一起動 ★ 別把它當常數 ────
 * 兵量來自 hostScale[名義階]，名義階來自功績。所以 career/ranks.ts
 * 一改，這張表就要用 `scripts/benchmark.ts` 重量一次 ——
 * 上一版的表（兵量 191/312/452/685）就是這樣過期的。
 *
 * 第五章之後沒有內容，按每章 ×1.5 兵力 ／ ×1.45 輸出外推。
 */
