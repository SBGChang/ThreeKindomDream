  commandChanceByStage: {
    stranger: 0, acquainted: 0.15, friendly: 0.30, close: 0.50, sworn: 0.70,
  },
  troopsBase: 120,
  supplyBase: 120,
  // 沿用 `trainingCurve.crossLineRatio` 的形狀與數值。0.5 那一項自帶
  // 防退化底線：純武官的糧量有近八成來自他自己的武官階，
  // 因此「零糧秣」不可能出現 —— 不需要另加基底常數。
  crossLineRatio: 0.5,
  // 0–100 尺度下 50 ＝ ×1.0、100 ＝ ×2.0。四維買的是【倍率】，
  // 官階買的是【規模】，兩者相乘 —— 所以兩邊都不可缺。
  actorDivisor: 50,
  /**
   * 敵方兵力 ＝ 一關要打幾回合 ★
   *
   * 反推：平手關（troopsMul 1.0）要打【約五回合】。
   * 我方每回合輸出 ≈ 兵量上限 × 招的 ratio × (主維/50) × 1.9 招 ＋ 指揮，
   * rank 1 約 138、rank 7 約 1250 —— 乘五就是這條曲線。
   *
   * ── 為什麼要五回合而不是兩回合 ★★ ────────────────
   * 這是這一版最重要的一個數值決定。
   *
   * 兩回合的仗，勝負幾乎完全由「這回合放了幾招」（1／2／3，28%／54%／18%）
   * 決定 —— 擲骰的變異比估計值本身還大。於是「算得剛剛好就上」實際上
   * 是輸一半，貪心因此永遠不划算：實測 risk-seeking 只拿到
   * risk-averse 的 56% 點數（4765 對 8554）。
   *
   * 五回合之後大數法則開始作用，估計值變得可信 ——
   * **玩家算得出來的東西，才值得他去算。** push-your-luck 的整個前提
   * 就是「你可以判斷」，而判斷要能成立，變異就不能蓋過訊號。
   *
   * 代價是戰鬥變長（滿七關約 55 回合）。掃蕩與戰報預設收起就是為了它。
   */
