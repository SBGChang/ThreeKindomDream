  /**
   * 敵方每回合輸出 ＝ 一關要掉多少血 ★ **已 ×2.6 —— 這是難度的旋鈕**
   *
   * 與兵力【分開訂】，而這次的校準就是靠這條分離：
   *   兵力 → 一關要打幾回合（33 §5.4 訂在五回合，那是估算的前提）
   *   輸出 → 一關要掉多少血
   *
   * 「第一輪只打到第二三關」這個要求要更【難】、不要更【長】，
   * 所以只能動輸出。實測改兵力（×2.2）的下場是第一關要打十一回合 ——
   * 難度到了，但一關五回合那條規格沒了。
   *
   * ── 實測（13 策略 × 300 輪，第一輪、無天命加成）★ ────
   *   ×1.0  戰役深度 4.46–5.83   ← 太深
   *   ×2.6  戰役深度 **2.57–3.82**  ← 目標「打到 2、3 關就打不下去」
   *
   * 四維同時落到位：專精者一個 A 或 B（智85／武83）其餘 D，
   * 均衡者四維全在 C（74/67/64/60）換到五條特質。
   * 那正是「第一輪還沒有天命能力」該有的樣子。
   */
