/**
 * 戰役的規則（33）★ 全部 GREYBOX。
 *
 * ── 主角的施放次數 ──────────────────────────────────
 * `[1, 0.6, 0.3]` ＝ 保底一招 ＋ 第二招 60% ＋ 第三招 30%，三次獨立擲：
 *
 *   1 招 28% ／ **2 招 54%** ／ 3 招 18%　→ 期望 1.9 招／回合
 *
 * 第一項必須是 1 —— **保底一招**是機制本體（下限由玩家自己保證），
 * 由載入期驗證強制。
 *
 * 而「先擲次數、再抽哪一招、同回合不重複」讓三格的期望上場率相同
 * （各約 0.63 次／回合）。於是配置從「排優先序」變成【設計一組組合】——
 * 三招之間必須各自成立，因為你不知道哪一招會出。
 *
 * ── 指揮傳令的機率 ──────────────────────────────────
 * 三人同階的期望：相識 0.45 ／ 友好 0.90 ／ 知交 1.50 ／ 莫逆 2.10。
 * 加上主角的 1.9，從相識到莫逆【一回合的行動數幾乎翻倍】，
 * 而且過半數的行動來自別人 —— 好感因此不再是一個百分比加成，
 * 而是「你的軍隊每回合能做幾件事」。
 *
 * `baseStartAffinity = 20` 表示所有人開局就在相識，因此第一場戰役
 * 就偶爾有人傳令來，不會是死的。
 *
 * ── 敵方曲線 ★ ──────────────────────────────────────
 * `enemyTroopsByRank` 索引【官階】不索引章節（D25）—— 這是 17 §6.4 已立的
 * 規矩：難度與報酬必須一起長，否則壓低某一線的官階會變成刷簡單高報酬的農場。
 *
 * 基準取自兵量的量級：灰盒四章單線約 2200 功績 → rank 7，
 * 兵量係數 ≈ 7.7 × troopsBase 120 ≈ 920。第一關的 troopsMul 0.55
 * 讓玩家在 rank 7 時大約三、四回合清掉 —— 前段是碾過去的，後段才是拚的。
 *
 * **完全未測。** 校準見 RFC-01 §6。
 */
