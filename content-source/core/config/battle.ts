import type { BattleRuleDef } from '../../../src/contracts/core/definitions.js';
import { coreDef } from '../pack-id.js';

/**
 * 戰役的規則（33）★ 全部 GREYBOX。
 *
 * ── 主角的施放次數 ──────────────────────────────────
 * `[1, 0.6, 0.3]` ＝ 保底一招 ＋ 第二招 60% ＋ 第三招 30%，三次獨立擲：
 *
 *   1 招 28% ／ **2 招 54%** ／ 3 招 18%　→ 期望 1.9 招／回合
 *
 * 第一項必須是 1 —— **保底一招**是機制本體（下限由玩家自己保證），
 * 由載入期驗證強制。
 *
 * 而「先擲次數、再抽哪一招、同回合不重複」讓三格的期望上場率相同
 * （各約 0.63 次／回合）。於是配置從「排優先序」變成【設計一組組合】——
 * 三招之間必須各自成立，因為你不知道哪一招會出。
 *
 * ── 指揮傳令的機率 ──────────────────────────────────
 * 三人同階的期望：相識 0.45 ／ 友好 0.90 ／ 知交 1.50 ／ 莫逆 2.10。
 * 加上主角的 1.9，從相識到莫逆【一回合的行動數幾乎翻倍】，
 * 而且過半數的行動來自別人 —— 好感因此不再是一個百分比加成，
 * 而是「你的軍隊每回合能做幾件事」。
 *
 * `baseStartAffinity = 20` 表示所有人開局就在相識，因此第一場戰役
 * 就偶爾有人傳令來，不會是死的。
 *
 * ── 敵方曲線 ★ ──────────────────────────────────────
 * `enemyTroopsByRank` 索引【官階】不索引章節（D25）—— 這是 17 §6.4 已立的
 * 規矩：難度與報酬必須一起長，否則壓低某一線的官階會變成刷簡單高報酬的農場。
 *
 * 基準取自兵量的量級：灰盒四章單線約 2200 功績 → rank 7，
 * 兵量係數 ≈ 7.7 × troopsBase 120 ≈ 920。第一關的 troopsMul 0.55
 * 讓玩家在 rank 7 時大約三、四回合清掉 —— 前段是碾過去的，後段才是拚的。
 *
 * **完全未測。** 校準見 RFC-01 §6。
 */
export const battleRule: BattleRuleDef = coreDef('battleRule', 'battle:main', {
  castChances: [1, 0.6, 0.3],
  commandChanceByStage: {
    stranger: 0, acquainted: 0.15, friendly: 0.30, close: 0.50, sworn: 0.70,
  },
  troopsBase: 120,
  supplyBase: 120,
  // 沿用 `trainingCurve.crossLineRatio` 的形狀與數值。0.5 那一項自帶
  // 防退化底線：純武官的糧量有近八成來自他自己的武官階，
  // 因此「零糧秣」不可能出現 —— 不需要另加基底常數。
  crossLineRatio: 0.5,
  // 0–100 尺度下 50 ＝ ×1.0、100 ＝ ×2.0。四維買的是【倍率】，
  // 官階買的是【規模】，兩者相乘 —— 所以兩邊都不可缺。
  actorDivisor: 50,
  enemyTroopsByRank: [180, 260, 380, 540, 760, 1050, 1450, 1980, 2680, 3600, 4800, 6300],
  /**
   * 敵方每回合輸出 ＝ 敵方兵力 × 這個比例 × 該關的 damageMul。
   *
   * ── 從 0.10 調到 0.06 ★ 實測依據 ──────────────────
   * 0.10 時第一章的玩家（兵量 180、武 E）在第四關就必死：
   * 敵兵 243 要打三回合，而對面每回合 32 —— 三回合就是 96，
   * 他的軍勢在前三關已經只剩八成。實測「通過章節 平均 0.23」，
   * 也就是【幾乎所有人都死在第一場戰役】。
   *
   * 0.06 之後同一關約 19／回合、三回合 59，第一章的玩家大約打到第四關 ——
   * 「前三關碾過去、第四關開始要想」正是七關該有的節奏。
   */
  enemyDamageRatio: 0.06,
  // 恢復 1 點軍勢消耗 1 點糧秣 —— 於是【糧量就是「你能把軍隊填回多少」】。
  // 有效血量 = 兵量 + 糧量 ×（政 / 50），三條官途在政 = 50 時完全相等，
  // 差別只在形狀（33 §5.3）。
  supplyPerTroop: 1,
  rallyRatio: 0.35,
  // 安全閥，不是玩法上的回合上限（D9 明確不做那個）：
  // 若玩家一招輸出都沒有，戰鬥不能無限跑。
  maxTurns: 40,
});
